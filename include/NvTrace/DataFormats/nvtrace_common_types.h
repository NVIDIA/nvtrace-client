/// \brief Descriptor for a single CPU timing code location.
struct NvTrace_CpuTimingDescriptor
{
    /// Name of the code location being timed.
    char name[64];
    /// The number of bits the TSC was preshifted before exponentiation;
    /// used in post-processing to calculate histogram bucket splits.
    uint32_t preshift;
};
#define NvTrace_CpuTimingDescriptor_MINOR_VERSION_A NVTRACE_FIELD_END_OFFSET(NvTrace_CpuTimingDescriptor, preshift)

#define NVTRACE_TIMING_HISTOGRAM_COUNT 64

/// \brief Timing values for a single CPU code location.
struct NvTrace_CpuTimingEntry
{
    /// A timing histogram, where each bucket index = log(duration >> preshift, 2^(1/3)).
    uint64_t durationHistogram[NVTRACE_TIMING_HISTOGRAM_COUNT];
};
#define NvTrace_CpuTimingEntry_MINOR_VERSION_A NVTRACE_FIELD_END_OFFSET(struct NvTrace_CpuTimingEntry, durationHistogram)


