/// Bitfield macros
#define NVTRACE_FIELD_RANGE_START(field) (0?field)
#define NVTRACE_FIELD_RANGE_END(field) (1?field)
#define NVTRACE_FIELD_RANGE_SIZE(field) (NVTRACE_FIELD_RANGE_END(field) - NVTRACE_FIELD_RANGE_START(field) + 1)
#define NVTRACE_FIELD_SHIFT(field) NVTRACE_FIELD_RANGE_START(field)
#define NVTRACE_FIELD_MASK32_UNSHIFTED(field) (0xFFFFFFFF >> (32 - NVTRACE_FIELD_RANGE_SIZE(field)))
#define NVTRACE_FIELD_MASK32(field) (NVTRACE_FIELD_MASK32_UNSHIFTED(field) << NVTRACE_FIELD_SHIFT(field))
#define NVTRACE_FIELD_MASK64_UNSHIFTED(field) (0xFFFFFFFFFFFFFFFF >> (64 - NVTRACE_FIELD_RANGE_SIZE(field)))
#define NVTRACE_FIELD_MASK64(field) (NVTRACE_FIELD_MASK64_UNSHIFTED(field) << NVTRACE_FIELD_SHIFT(field))

#define NVTRACE_GETFIELD32(reg, field) (((reg) & NVTRACE_FIELD_MASK32(field)) >> NVTRACE_FIELD_SHIFT(field))
#define NVTRACE_SETFIELD32_UNCHECKED(reg, field, val) (((reg) & ~NVTRACE_FIELD_MASK32(field)) | (((uint32_t)(val)) << NVTRACE_FIELD_SHIFT(field)))
#define NVTRACE_SETFIELD32(reg, field, val) NVTRACE_SETFIELD32_UNCHECKED(reg, field, (val) & NVTRACE_FIELD_MASK32_UNSHIFTED(field))

#define NVTRACE_GETFIELD64(reg, field) (((reg) & NVTRACE_FIELD_MASK64(field)) >> NVTRACE_FIELD_SHIFT(field))
#define NVTRACE_SETFIELD64_UNCHECKED(reg, field, val) (((reg) & ~NVTRACE_FIELD_MASK64(field)) | (((uint64_t)(val)) << NVTRACE_FIELD_SHIFT(field)))
#define NVTRACE_SETFIELD64(reg, field, val) NVTRACE_SETFIELD64_UNCHECKED(reg, field, (val) & NVTRACE_FIELD_MASK64_UNSHIFTED(field))

/// Size calculation for consistent struct versioning
#define NVTRACE_FIELD_END_OFFSET(type_, lastfield_) ((uint32_t)(offsetof(type_, lastfield_) + sizeof(((type_*)0)->lastfield_)))
#define NVTRACE_FIELD_EXISTS(pObject_, field_) ((pObject_)->structSize >= (const size_t)((const uint8_t*)(&(pObject_)->field_) + sizeof((pObject_)->field_) - (const uint8_t*)(pObject_)))

