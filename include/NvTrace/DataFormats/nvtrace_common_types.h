/// \brief Provider's overall status.
///
/// These can be rolled up, with a trump order of
///     uninitialized < armed < measuring < recovering < faulted
enum NvTrace_ProviderStatus
{
    /// The initial state of a provider.  Observers never see this.
    NvTrace_ProviderStatus_uninitialized = 0,

    /// The provider is ready to be activated, but no output is flowing.
    NvTrace_ProviderStatus_armed = 100,

    /// Output is flowing into circular buffers.
    NvTrace_ProviderStatus_measuring = 200,

    /// An internal error has occurred, but recovery is in progress.
    NvTrace_ProviderStatus_recovering = 300,

    /// An irrecoverable error has occurred.
    NvTrace_ProviderStatus_faulted = 400,

    /// The provider is paused, yielding to another tool (like Nsight/CUPTI).
    NvTrace_ProviderStatus_yielding = 500,

    NvTrace_ProviderStatus_FORCE_INT = 0x7fffffff
};

